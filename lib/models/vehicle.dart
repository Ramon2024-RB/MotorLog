class Vehicle {
  final String id;
  final String name;
  final String brand;
  final String model;
  final int year;
  final String fuelType;
  final int mileage;

  const Vehicle({
    required this.id,
    required this.name,
    required this.brand,
    required this.model,
    required this.year,
    required this.fuelType,
    required this.mileage,
  });
}